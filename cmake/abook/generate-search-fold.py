"""Regenerate search-fold-data.h using Python with Unicode 15.1.0 tables."""

import unicodedata


def folded(char):
    decomposed = unicodedata.normalize("NFD", char)
    folded = unicodedata.normalize("NFD", decomposed.casefold())
    return "".join(part for part in folded if part.isalnum())


def main():
    if unicodedata.unidata_version != "15.1.0":
        raise SystemExit("This generator requires Unicode 15.1.0 data")

    print("/* Generated by generate-search-fold.py. See Unicode-LICENSE.txt. */")
    print("static const struct fold_range fold_ranges[] = {")
    start = None
    for point in range(0x110000):
        char = chr(point)
        # Hangul syllables are canonically decomposed by the C code.
        key = "" if 0xAC00 <= point <= 0xD7A3 else folded(char)
        if key == char:
            if start is None:
                start = point
            continue
        if start is not None:
            print(f"\t{{ 0x{start:X}, 0x{point - 1:X}, NULL }},")
            start = None
        if key:
            encoded = key.encode("utf-8")
            assert len(encoded) <= 3 * len(char.encode("utf-8"))
            literal = "".join(f"\\x{byte:02X}" for byte in encoded)
            print(f'\t{{ 0x{point:X}, 0x{point:X}, "{literal}" }},')
    assert start is None
    print("};")


if __name__ == "__main__":
    main()
